#!/bin/bash
# Поиск файлов по расширению и минимальному размеру.
# Использование: ./find_files.sh <каталог> <расширение> <мин_размер_в_байтах>
# Пример:        ./find_files.sh 01 txt 1000

# 1. Проверка количества аргументов
if [ $# -ne 3 ]; then
    echo "Использование: $0 <каталог> <расширение> <мин_размер_в_байтах>" >&2
    exit 1
fi

dir="$1"
ext="${2#.}"      # убираем точку, если ввели ".txt" вместо "txt"
min="$3"

# 2. Проверка аргументов
if [ ! -d "$dir" ]; then
    echo "Ошибка: каталог '$dir' не найден" >&2
    exit 2
fi
if ! [[ "$min" =~ ^[0-9]+$ ]]; then
    echo "Ошибка: размер должен быть целым числом байт, получено '$min'" >&2
    exit 3
fi

# 3. Поиск, вывод и сортировка
echo "РАЗМЕР     ИЗМЕНЁН          ПУТЬ"
find "$dir" -type f -name "*.$ext" \( -size +"${min}c" -o -size "${min}c" \) \
     -printf '%-10s %TY-%Tm-%Td %TH:%TM %p\n' \
  | sort -n
